func setupTestRepo(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()

	// Structure:
	// dir/
	//   .git/
	//   .ap/
	//     go.yaml
	//   go.mod
	//   main.go
	//   main_test.go
	//   generated.go ("// Code generated ... DO NOT EDIT.")
	//   vendor/
	//     lib/
	//       lib.go
	//   k8s/
	//     manifest.yaml
	//     crds/
	//       crd.yml
	//   images/
	//     app/
	//       Dockerfile
	//   sub/
	//     .ap/
	//     go.mod
	//     sub.go
	//     images/
	//       subapp/
	//         Dockerfile
	//     k8s/
	//       sub.yaml
	//   skipped/
	//     .ap/
	//     go.mod
	//     skipped.go
	//     skipped_test.go
	//     images/
	//       skip/
	//         Dockerfile
	//     k8s/
	//       skip.yaml

	files := map[string]string{
		".ap/go.yaml": `skip:
  - skipped/**
`,
		"go.mod":                         "module example.com/root\n\ngo 1.26\n",
		"main.go":                        "package main\n\nfunc main() {}\n",
		"main_test.go":                   "package main\n\nimport \"testing\"\nfunc TestMain(t *testing.T) {}\n",
		"generated.go":                   "// Code generated by tool. DO NOT EDIT.\npackage main\n",
		"vendor/lib/lib.go":              "package lib\n",
		"k8s/manifest.yaml":              "apiVersion: v1\nkind: ConfigMap\n",
		"k8s/crds/crd.yml":               "apiVersion: v1\nkind: CustomResourceDefinition\n",
		"images/app/Dockerfile":          "FROM alpine\n",
		"sub/.ap/ap.yaml":                "",
		"sub/go.mod":                     "module example.com/root/sub\n\ngo 1.26\n",
		"sub/sub.go":                     "package sub\n",
		"sub/images/subapp/Dockerfile":   "FROM alpine\n",
		"sub/k8s/sub.yaml":               "apiVersion: v1\nkind: Pod\n",
		"skipped/.ap/ap.yaml":            "",
		"skipped/go.mod":                 "module example.com/root/skipped\n\ngo 1.26\n",
		"skipped/skipped.go":             "package skipped\n",
		"skipped/skipped_test.go":        "package skipped\n",
		"skipped/images/skip/Dockerfile": "FROM alpine\n",
		"skipped/k8s/skip.yaml":          "apiVersion: v1\nkind: Pod\n",
	}

	for rel, content := range files {
		full := filepath.Join(dir, rel)
		if err := os.MkdirAll(filepath.Dir(full), 0755); err != nil {
			t.Fatalf("MkdirAll failed: %v", err)
		}
		if err := os.WriteFile(full, []byte(content), 0644); err != nil {
			t.Fatalf("WriteFile failed: %v", err)
		}
	}

	// Create .git dir
	if err := os.MkdirAll(filepath.Join(dir, ".git"), 0755); err != nil {
		t.Fatalf("failed to create .git: %v", err)
	}

	return dir
}

func TestRepoSingleWalkAndCache(t *testing.T) {
	ResetCache()
	dir := setupTestRepo(t)

	r1, err := Open(dir)
	if err != nil {
		t.Fatalf("Open failed: %v", err)
	}

	if count := WalkCount(); count != 1 {
		t.Fatalf("expected WalkCount=1, got %d", count)
	}

	// Second Open of the same root should use cache without walking
	r2, err := Open(dir)
	if err != nil {
		t.Fatalf("Open second time failed: %v", err)
	}
	if r1 != r2 {
		t.Fatalf("expected same repo pointer from cache")
	}
	if count := WalkCount(); count != 1 {
		t.Fatalf("expected WalkCount to remain 1, got %d", count)
	}

	// Opening a subdirectory should reuse cached parent repo view without walking
	subDir := filepath.Join(dir, "sub")
	rSub, err := Open(subDir)
	if err != nil {
		t.Fatalf("Open subDir failed: %v", err)
	}
	if count := WalkCount(); count != 1 {
		t.Fatalf("expected WalkCount to remain 1 after opening subDir, got %d", count)
	}
	if rSub.Root() != subDir {
		t.Fatalf("expected rSub.Root()=%s, got %s", subDir, rSub.Root())
	}
}

func TestAPRootsAndModules(t *testing.T) {
	ResetCache()
	dir := setupTestRepo(t)

	r, err := Open(dir)
	if err != nil {
		t.Fatalf("Open failed: %v", err)
	}

	expectedAPRoots := []string{
		dir,
		filepath.Join(dir, "sub"),
	}
	gotAPRoots := r.APRoots()
	sort.Strings(expectedAPRoots)
	sort.Strings(gotAPRoots)
	if !reflect.DeepEqual(gotAPRoots, expectedAPRoots) {
		t.Errorf("APRoots() = %v, want %v", gotAPRoots, expectedAPRoots)
	}

	expectedModules := []string{
		dir,
		filepath.Join(dir, "sub"),
	}
	gotModules := r.Modules()
	sort.Strings(expectedModules)
	sort.Strings(gotModules)
	if !reflect.DeepEqual(gotModules, expectedModules) {
		t.Errorf("Modules() = %v, want %v", gotModules, expectedModules)
	}
}

func TestSkipUniformlyApplied(t *testing.T) {
	ResetCache()
	dir := setupTestRepo(t)

	r, err := Open(dir)
	if err != nil {
		t.Fatalf("Open failed: %v", err)
	}

	// The skipped/ directory MUST NOT appear anywhere in the tree
	for _, f := range r.Files() {
		if filepath.Base(filepath.Dir(f.Path)) == "skipped" || filepath.Base(f.Path) == "skipped" {
			t.Fatalf("skipped file leaked into tree: %s", f.Path)
		}
	}
	for _, d := range r.Dirs() {
		if filepath.Base(d) == "skipped" {
			t.Fatalf("skipped dir leaked into tree: %s", d)
		}
	}

	for _, ap := range r.APRoots() {
		if filepath.Base(ap) == "skipped" {
			t.Fatalf("skipped AP root leaked into APRoots(): %s", ap)
		}
	}

	for _, mod := range r.Modules() {
		if filepath.Base(mod) == "skipped" {
			t.Fatalf("skipped module leaked into Modules(): %s", mod)
		}
	}

	// HasGoTests in skipped should be false
	if r.HasGoTests(filepath.Join(dir, "skipped")) {
		t.Errorf("HasGoTests(skipped) should be false")
	}

	// FindDockerfiles must not include skipped Dockerfile
	for _, df := range r.FindDockerfiles() {
		if filepath.Base(filepath.Dir(filepath.Dir(df))) == "skipped" {
			t.Fatalf("skipped Dockerfile found: %s", df)
		}
	}

	// FindManifests must not include skipped manifest
	for _, m := range r.FindManifests() {
		if filepath.Base(filepath.Dir(filepath.Dir(m))) == "skipped" {
			t.Fatalf("skipped manifest found: %s", m)
		}
	}
}

func TestFileClassification(t *testing.T) {
	ResetCache()
	dir := setupTestRepo(t)

	r, err := Open(dir)
	if err != nil {
		t.Fatalf("Open failed: %v", err)
	}

	mainTest := r.File("main_test.go")
	if mainTest == nil || !mainTest.IsTest() {
		t.Errorf("expected main_test.go to be IsTest() = true")
	}

	mainGo := r.File("main.go")
	if mainGo == nil || mainGo.IsTest() {
		t.Errorf("expected main.go to be IsTest() = false")
	}

	genGo := r.File("generated.go")
	if genGo == nil || !genGo.IsGenerated() {
		t.Errorf("expected generated.go to be IsGenerated() = true")
	}
	if mainGo.IsGenerated() {
		t.Errorf("expected main.go to be IsGenerated() = false")
	}

	// vendor directory is ignored during walk, so vendor/lib/lib.go should not exist
	if r.File("vendor/lib/lib.go") != nil {
		t.Errorf("vendor files should have been ignored during walk")
	}
}

func TestFindDockerfilesAndManifests(t *testing.T) {
	ResetCache()
	dir := setupTestRepo(t)

	r, err := Open(dir)
	if err != nil {
		t.Fatalf("Open failed: %v", err)
	}

	// For root: only images/app/Dockerfile (sub/images/subapp/Dockerfile belongs to sub AP root)
	rootDockerfiles := r.FindDockerfiles()
	expectedRootDockerfiles := []string{filepath.Join(dir, "images", "app", "Dockerfile")}
	if !reflect.DeepEqual(rootDockerfiles, expectedRootDockerfiles) {
		t.Errorf("FindDockerfiles() = %v, want %v", rootDockerfiles, expectedRootDockerfiles)
	}

	// Under sub:
	subDockerfiles := r.Under(filepath.Join(dir, "sub")).FindDockerfiles()
	expectedSubDockerfiles := []string{filepath.Join(dir, "sub", "images", "subapp", "Dockerfile")}
	if !reflect.DeepEqual(subDockerfiles, expectedSubDockerfiles) {
		t.Errorf("sub FindDockerfiles() = %v, want %v", subDockerfiles, expectedSubDockerfiles)
	}

	// Manifests for root (excluding sub)
	rootManifests := r.FindManifests()
	expectedRootManifests := []string{
		filepath.Join(dir, "k8s", "crds", "crd.yml"),
		filepath.Join(dir, "k8s", "manifest.yaml"),
	}
	if !reflect.DeepEqual(rootManifests, expectedRootManifests) {
		t.Errorf("FindManifests() = %v, want %v", rootManifests, expectedRootManifests)
	}

	// Manifests for sub
	subManifests := r.Under(filepath.Join(dir, "sub")).FindManifests()
	expectedSubManifests := []string{
		filepath.Join(dir, "sub", "k8s", "sub.yaml"),
	}
	if !reflect.DeepEqual(subManifests, expectedSubManifests) {
		t.Errorf("sub FindManifests() = %v, want %v", subManifests, expectedSubManifests)
	}
}

func TestGlobAndQueries(t *testing.T) {
	ResetCache()
	dir := setupTestRepo(t)

	r, err := Open(dir)
	if err != nil {
		t.Fatalf("Open failed: %v", err)
	}

	// Glob
	matches := r.Glob("k8s/*.yaml")
	expectedMatches := []string{filepath.Join(dir, "k8s", "manifest.yaml")}
	if !reflect.DeepEqual(matches, expectedMatches) {
		t.Errorf("Glob(k8s/*.yaml) = %v, want %v", matches, expectedMatches)
	}

	// HasGoTests
	if !r.HasGoTests() {
		t.Errorf("HasGoTests() expected true")
	}
	if r.HasGoTests(filepath.Join(dir, "sub")) {
		t.Errorf("HasGoTests(sub) expected false (sub has no _test.go)")
	}

	// HasGoFiles
	if !r.HasGoFiles() {
		t.Errorf("HasGoFiles() expected true")
	}
	if !r.Under(filepath.Join(dir, "sub")).HasGoFiles() {
		t.Errorf("sub HasGoFiles() expected true")
	}
}
